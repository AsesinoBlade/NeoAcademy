/**
 * Write one section of an ebook.
 *
 * POST /api/generate/book-section
 *   { bookId, sectionId, referenceMaterial?, userProfile? }
 *   headers: model selection (x-model ...), x-image-generation-enabled
 *
 * Reads the outline from data/books/<id>/book.json, writes the section as
 * Markdown to data/books/<id>/sections/<sectionId>.md and returns stats.
 * Already-written sections are returned as-is (idempotent, resume-safe).
 */
import { type NextRequest } from 'next/server';

import { streamLLM } from '@/lib/ai/llm';
import { buildPrompt, PROMPT_IDS } from '@/lib/generation/prompts';
import { createLogger } from '@/lib/logger';
import { apiError, apiSuccess } from '@/lib/server/api-response';
import { resolveGenerationModelFromHeaders } from '@/lib/server/resolve-model';
import { sanitiseSectionFigures } from '@/lib/book/figures';
import { extractClaims } from '@/lib/book/llm';
import { buildProjectContext, extractProjectFilesDetailed, recordProjectFiles } from '@/lib/book/project';
import { formatEvidence, gatherEvidence } from '@/lib/book/references';
import { formatPremises, formatPrinciples, readPrinciples } from '@/lib/book/principles';
import {
  countWords,
  listSectionRefs,
  readBook,
  readSection,
  writeSection,
} from '@/lib/book/storage';

const log = createLogger('Book Section API');

export const runtime = 'nodejs';
export const maxDuration = 900;

const SECTION_MAX_OUTPUT_TOKENS = Number.parseInt(
  process.env.BOOK_SECTION_MAX_OUTPUT_TOKENS || '12000',
  10,
);
const MIN_SECTION_WORDS = 350;

const IMAGE_INSTRUCTIONS_ENABLED = `**Illustration / picture** — generated by an image model. Image models CANNOT render readable text, so pictures are only for things that look right without any words or exact detail: physical objects, equipment, places, people at work, nature, historical scenes, or a conceptual/metaphorical illustration.

NEVER use a picture for anything that must be exact or readable — use the right figure type instead:
- screenshots, user interfaces, windows, dialogs, IDEs, terminals, command output → a code block (\`\`\`text / \`\`\`bash) showing the exact content
- file/directory trees, project layouts → a \`\`\`text code block drawn with ├── └──
- source code, config files → a code block
- diagrams, flowcharts, architectures, relationships, processes → a \`mermaid\` diagram
- grids, boards, tables, matrices, puzzles with numbers → a Markdown table (or \`\`\`text block)
- anything with numbers, labels, axes or data → a \`chart\` or a table

Describe the picture concretely; never ask for text, labels, numbers or code inside it:

\`\`\`image
{"prompt": "Photorealistic close-up of ..., soft natural light, shallow depth of field", "caption": "What the picture shows and why it matters.", "aspect": "16:9"}
\`\`\``;

const IMAGE_INSTRUCTIONS_DISABLED =
  '**Pictures are not available for this book** — do not output `image` blocks. Use charts, diagrams and tables instead.';

function stripThinking(text: string): string {
  return text.replace(/<think>[\s\S]*?<\/think>/gi, '').replace(/^\s*<\/?think>\s*/gi, '');
}

/** Remove wrappers a model sometimes adds: ```markdown fences, a repeated title. */
function cleanSectionText(text: string, sectionTitle: string): string {
  let out = stripThinking(text).trim();
  const fenced = out.match(/^```(?:markdown|md)?\s*\n([\s\S]*?)\n```\s*$/i);
  if (fenced) out = fenced[1].trim();

  const firstLine = out.split('\n')[0] ?? '';
  const normalise = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  if (/^#{1,3}\s/.test(firstLine) && normalise(firstLine.replace(/^#+\s*/, '')).includes(normalise(sectionTitle))) {
    out = out.split('\n').slice(1).join('\n').trim();
  }
  return out;
}

export async function POST(req: NextRequest) {
  try {
    const body = (await req.json()) as {
      bookId: string;
      sectionId: string;
      referenceMaterial?: string;
      userProfile?: string;
      /** Look up the section's key identifiers in local docs / web before writing. */
      factCheck?: boolean;
      webSearch?: boolean;
    };
    if (!body.bookId || !body.sectionId) {
      return apiError('MISSING_REQUIRED_FIELD', 400, 'bookId and sectionId are required');
    }

    const book = await readBook(body.bookId);
    if (!book) return apiError('INVALID_REQUEST', 404, 'Book not found');

    const refs = listSectionRefs(book.outline);
    const ref = refs.find((r) => r.id === body.sectionId);
    if (!ref) return apiError('INVALID_REQUEST', 400, `Unknown section ${body.sectionId}`);

    const existing = await readSection(book.id, ref.id);
    if (existing) {
      return apiSuccess({ sectionId: ref.id, words: countWords(existing), skipped: true });
    }

    const chapter = book.outline[ref.chapterIndex];
    const chapterRefs = refs.filter((r) => r.chapterIndex === ref.chapterIndex);
    const isLastInChapter = chapterRefs[chapterRefs.length - 1]?.id === ref.id;
    const isSummary = /summary|exercise|review/i.test(ref.title);

    // Continuity: the end of the previous section (in book order).
    const previousRef = refs[refs.indexOf(ref) - 1];
    const previousText = previousRef ? await readSection(book.id, previousRef.id) : null;
    const previousSectionTail = previousText
      ? `(${previousRef!.sectionNumber} ${previousRef!.title})\n...${previousText.slice(-1800)}`
      : 'This is the first section of the book.';

    const previousInChapter = chapterRefs
      .filter((r) => r.sectionIndex < ref.sectionIndex)
      .map((r) => `- ${r.sectionNumber} ${r.title}: ${r.spec}`)
      .join('\n');

    const tableOfContents = book.outline
      .map((ch, ci) => {
        const sections = refs
          .filter((r) => r.chapterIndex === ci)
          .map((r) => `   ${r.sectionNumber} ${r.title}`)
          .join('\n');
        return `${ci + 1}. ${ch.title}\n${sections}`;
      })
      .join('\n');

    const imagesEnabled = req.headers.get('x-image-generation-enabled') === 'true';

    // Running project: canonical spec + current files (bigger budget for the
    // final chapter, which assembles the whole project).
    const isFinalChapter = ref.chapterIndex === book.outline.length - 1;
    const projectContext = book.projectSpec
      ? await buildProjectContext(
          book.id,
          book.projectSpec,
          `${ref.spec}\n${chapter.teachingNotes || ''}`,
          isFinalChapter ? 26000 : 14000,
        )
      : '';

    // Grounding before writing: verify the identifiers this section is about
    // (from its spec and the chapter brief) so the author doesn't build a
    // section around something that doesn't exist.
    let referenceNotes = 'None.';
    if (body.factCheck) {
      const claims = await extractClaims(
        req,
        `Section: ${ref.title}\n${ref.spec}\n\nChapter brief:\n${chapter.teachingNotes || ''}`,
        8,
      ).catch(() => []);
      if (claims.length > 0) {
        const evidence = await gatherEvidence(claims, {
          webSearch: !!body.webSearch,
          provider: (req.headers.get('x-web-search-provider') || undefined) as
            | import('@/lib/web-search/search').WebSearchProviderChoice
            | undefined,
        });
        referenceNotes = formatEvidence(evidence);
        const missing = evidence.filter((e) => e.verdict === 'not-found').map((e) => e.claim.identifier);
        if (missing.length) log.warn(`${ref.sectionNumber}: spec mentions non-existent ${missing.join(', ')}`);
      }
    }
    const targetWords = isSummary ? '900-1,400' : '1,600-2,300';

    const prompts = buildPrompt(PROMPT_IDS.BOOK_SECTION, {
      targetWords,
      imageInstructions: imagesEnabled ? IMAGE_INSTRUCTIONS_ENABLED : IMAGE_INSTRUCTIONS_DISABLED,
      bookTitle: book.title,
      bookSubtitle: book.subtitle ? `*${book.subtitle}*` : '',
      requirement: book.requirement,
      userProfile: body.userProfile || '',
      language: book.language,
      tableOfContents,
      chapterNumber: ref.chapterNumber,
      chapterTitle: chapter.title,
      chapterDescription: chapter.description || '',
      chapterBrief: chapter.teachingNotes || '(none)',
      previousSectionsInChapter: previousInChapter || '(none — this is the first section of the chapter)',
      previousSectionTail,
      referenceMaterial: body.referenceMaterial?.trim() || 'None provided — rely on your expert knowledge.',
      referenceNotes,
      premiseStance: book.premises?.length ? formatPremises(book.premises) : '(none — no premise check was run)',
      principles: formatPrinciples(await readPrinciples(book.id)),
      projectContext: projectContext
        ? `## The running project (follow exactly)\n\n${projectContext}`
        : '',
      sectionNumber: ref.sectionNumber,
      sectionTitle: ref.title,
      sectionSpec: ref.spec,
      sectionRole:
        isSummary || isLastInChapter
          ? 'This section closes the chapter: give crisp key takeaways, then graded exercises (from straightforward to challenging) with full worked solutions to at least half of them.'
          : '',
    });
    if (!prompts) return apiError('INTERNAL_ERROR', 500, 'Book section prompt not found');

    const { model, modelString } = resolveGenerationModelFromHeaders(req);
    log.info(`Writing ${ref.sectionNumber} "${ref.title}" for "${book.title}" [model=${modelString}]`);

    // Streaming avoids the ~5 min response-header timeout on long sections.
    const generate = async (system: string) => {
      const result = streamLLM(
        { model, system, prompt: prompts.user, maxOutputTokens: SECTION_MAX_OUTPUT_TOKENS },
        'book-section',
      );
      let text = '';
      for await (const chunk of result.textStream) text += chunk;
      return cleanSectionText(text, ref.title);
    };

    let markdown = await generate(prompts.system);
    if (countWords(markdown) < MIN_SECTION_WORDS) {
      log.warn(`Section ${ref.sectionNumber} too short (${countWords(markdown)} words) — retrying once`);
      markdown = await generate(
        prompts.system +
          `\n\n## IMPORTANT\nYour previous attempt was far too short. Write the full ${targetWords} words of section body now.`,
      );
    }
    if (countWords(markdown) < MIN_SECTION_WORDS) {
      return apiError('GENERATION_FAILED', 502, `Section ${ref.sectionNumber} came back too short`);
    }

    const cleaned = sanitiseSectionFigures(markdown, ref.id, { imagesEnabled });
    await writeSection(book.id, ref.id, cleaned.markdown);
    let projectFiles = 0;
    if (book.projectSpec) {
      const { files, decisions } = extractProjectFilesDetailed(
        cleaned.markdown,
        book.projectSpec.files.map((f) => f.path),
      );
      projectFiles = await recordProjectFiles(book.id, ref.id, files);
      const rejected = decisions.filter((d) => !d.accepted);
      if (rejected.length) {
        log.info(
          `${ref.sectionNumber}: ${rejected.length} File: block(s) not recorded as project state — ` +
            rejected.map((d) => `${d.path} (${d.reason})`).join('; '),
        );
      }
    }

    const words = countWords(cleaned.markdown);
    log.info(
      `Wrote ${ref.sectionNumber}: ${words} words, ${cleaned.charts} chart(s), ${cleaned.diagrams} diagram(s), ` +
        `${cleaned.images} image(s)${cleaned.dropped ? `, dropped ${cleaned.dropped} invalid figure(s)` : ''}` +
        (projectFiles ? `, updated ${projectFiles} project file(s)` : ''),
    );

    return apiSuccess({
      sectionId: ref.id,
      words,
      charts: cleaned.charts,
      diagrams: cleaned.diagrams,
      images: cleaned.images,
      projectFiles,
    });
  } catch (error) {
    log.error('Book section generation failed:', error);
    return apiError('GENERATION_FAILED', 500, error instanceof Error ? error.message : String(error));
  }
}
